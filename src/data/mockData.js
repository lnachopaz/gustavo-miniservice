export const productosDestacados = productos.filter(p => p.destacado);
export const productosEnOferta   = productos.filter(p => p.oferta);

export function getProductoById(id) {
  return productos.find(p => p.id === Number(id));
}

export function getProductosByCategoria(slug) {
  const cat = categorias.find(c => c.slug === slug);
  if (!cat) return productos;
  return productos.filter(p => p.categoriaId === cat.id);
}

export function formatPrecio(precio) {
  return new Intl.NumberFormat('es-AR', {
    style: 'currency',
    currency: 'ARS',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(precio);
}
